"""Summarize measured packet and handover outcomes from a completed trial suite."""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import statistics


def summarize(run):
    log = (run / 'run.log').read_text()
    if 'Simulation time limit reached -- at t=35s' not in log:
        raise ValueError(f'Incomplete simulation: {run.name}')
    meta = json.loads((run / 'trial.json').read_text())
    scalar = (run / 'handover.sca').read_text()
    rates = re.findall(
        r'^scalar TrustGraphRoad\.server\.app\[\d+\] cbrGeneratedThroughput:simu5g_rateavg (\S+)$',
        scalar, re.MULTILINE)
    if len(rates) != meta['cars']:
        raise ValueError(f'Missing sender statistics: {run.name}')
    # Simu5G reports generated bytes per full run duration.
    payload = meta.get('payload_bytes', 100)
    blocks_per_slot = meta.get('blocks_per_slot', 50)
    sent = sum(round(float(rate) * 35 / payload) for rate in rates)
    delays, packets, cells, load = [], defaultdict(set), defaultdict(list), defaultdict(list)
    vectors = {}
    backlog = defaultdict(list)
    with (run / 'handover.vec').open() as stream:
        for line in stream:
            if line.startswith('vector '):
                _, serial, module, name, _ = line.split()
                if '.car[' in module and name == 'cbrRcvdPkt:vector':
                    vectors[serial] = ('received', module)
                elif '.car[' in module and name == 'cbrFrameDelay:vector':
                    vectors[serial] = ('delay', module)
                elif module.endswith('.nrConnectionControl') and name == 'servingCell:vector':
                    vectors[serial] = ('cell', module)
                elif module.endswith('.cellularNic.mac') and name == 'avgServedBlocksDl:vector':
                    vectors[serial] = ('load', module)
                elif module.endswith('.policy') and name in ('gnb1DlBacklogBytes', 'gnb2DlBacklogBytes'):
                    vectors[serial] = ('backlog', name[:4])
            elif line and line[0].isdigit():
                serial, _, time, value = line.split()
                if serial not in vectors:
                    continue
                kind, module = vectors[serial]
                if kind == 'delay':
                    delays.append(float(value) * 1000)
                elif kind == 'received':
                    packets[module].add(value)
                elif kind == 'cell':
                    cells[module].append((float(time), int(float(value))))
                elif kind == 'backlog':
                    backlog[module].append(int(float(value)))
                else:
                    load[module].append(float(value))

    if len(cells) != meta['cars'] or len(load) != 2 or any(len(series) != 35000 for series in load.values()):
        raise ValueError(f'Incomplete network vectors: {run.name}')
    received = sum(len(ids) for ids in packets.values())
    if not sent or received > sent:
        raise ValueError(f'Inconsistent packet counts: {run.name}')
    node_ids = dict(re.findall(
        r'^par (TrustGraphRoad\.car\[\d+\]\.cellularNic\.rrc\.nrConnectionControl) macNodeId (\d+)$',
        scalar, re.MULTILINE))
    handovers = reversals = 0
    actual_changes = set()
    for module, series in cells.items():
        transitions = [(time, old, new) for (_, old), (time, new)
                       in zip(series, series[1:]) if old and new and old != new]
        handovers += len(transitions)
        actual_changes.update((time, node_ids[module], new) for time, _, new in transitions)
        reversals += sum(new == origin and time - earlier <= 2.0
                         for (earlier, origin, _), (time, _, new) in zip(transitions, transitions[1:]))
    requests = [(float(time), ue, int(target)) for time, ue, target in re.findall(
        r'TRUSTGRAPH_DECISION (\S+) (\d+) \d+ (\d+) request', log)]
    completions = [(float(time), ue, int(target)) for time, ue, target in re.findall(
        r'TRUSTGRAPH_REQUEST_COMPLETED (\S+) (\d+) (\d+)', log)]
    for event in completions:
        if event not in actual_changes or not any(
            0 < event[0] - time <= 0.1 and event[1:] == (ue, target)
            for time, ue, target in requests
        ):
            raise ValueError(f'Uncorroborated policy handover: {run.name}, {event}')
    early_requests = [(float(time), ue) for time, ue in re.findall(r'TRUSTGRAPH_EARLY_REQUEST (\S+) (\d+)', log)]
    early_completions = [(float(time), ue, int(target)) for time, ue, target in re.findall(
        r'TRUSTGRAPH_EARLY_COMPLETED (\S+) (\d+) (\d+)', log)]
    for event in early_completions:
        if event not in completions or not any(0 < event[0] - time <= 0.1 and event[1] == ue
                                              for time, ue in early_requests):
            raise ValueError(f'Uncorroborated early handover: {run.name}, {event}')
    utilization = {
        cell: [sum(series[start:start + 100]) / (blocks_per_slot * 100)
               for start in range(0, 35000, 100)]
        for cell in ('gnb1', 'gnb2')
        for series in [load[f'TrustGraphRoad.{cell}.cellularNic.mac']]
    }
    if max(map(max, utilization.values())) > 1:
        raise ValueError(f'Allocated blocks exceed configured capacity: {run.name}')
    overload_by_cell = {cell: sum(value > 0.8 for value in series) / 10 for cell, series in utilization.items()}
    peak = max(map(max, utilization.values()))
    imbalance = sum(a > 0.8 and b < 0.5 for a, b in zip(utilization['gnb1'], utilization['gnb2'])) / 10
    first_offload = {}
    for time, ue, cell in sorted(actual_changes):
        if cell == 2:
            first_offload.setdefault(ue, time)
    if len(first_offload) >= 3:
        third = sorted(first_offload.values())[2]
        # The next complete 100 ms window excludes any slots before the move.
        after_index = int(third * 10) + 1
        paired_load = list(zip(utilization['gnb1'][after_index:], utilization['gnb2'][after_index:]))
        post_offload = {
            'third_distinct_handover_to_gnb2_s': third,
            'window_seconds': len(paired_load) / 10,
            'gnb2_below_80_seconds': sum(b < 0.8 for _, b in paired_load) / 10,
            'gnb1_above_80_while_gnb2_below_80_seconds': sum(a > 0.8 and b < 0.8 for a, b in paired_load) / 10,
            'gnb2_mean_dl_load': statistics.mean(b for _, b in paired_load) if paired_load else None,
        }
    else:
        post_offload = None
    if meta['split'] == 'stress' and any(len(backlog[cell]) != 349 for cell in utilization):
        raise ValueError(f'Missing RLC backlog samples: {run.name}')
    _, trial, condition, policy = run.name.split('-', maxsplit=3)
    return dict(trial=trial, condition=condition, policy=policy, sent=sent, received=received,
                packet_delivery_ratio=received / sent,
                mean_delay_ms=statistics.mean(delays) if delays else None,
                p95_delay_ms=statistics.quantiles(delays, n=20, method='inclusive')[18] if len(delays) > 1 else None,
                handovers=handovers, ping_pong_within_2s=reversals,
                overload_cell_seconds=round(sum(overload_by_cell.values()), 1),
                overload_seconds_by_cell=overload_by_cell,
                peak_dl_load=peak, gnb1_congested_gnb2_spare_seconds=imbalance,
                cell_peak_dl_load={cell: max(series) for cell, series in utilization.items()},
                cell_peak_dl_backlog_bytes={cell: max(series) for cell, series in backlog.items()},
                post_offload=post_offload,
                model_requests_completed=len(completions),
                model_requests_rejected=log.count('TRUSTGRAPH_REQUEST_REJECTED'),
                early_requests=len(early_requests), early_requests_completed=len(early_completions),
                bridge_timeouts=log.count('fallback_timeout'))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('suite', type=Path)
    suite = parser.parse_args().suite
    trials = [summarize(run) for run in sorted(suite.glob('trial-*')) if (run / 'finished').exists()]
    if not trials:
        raise ValueError('No completed simulations')
    groups = defaultdict(list)
    for row in trials:
        groups[(row['condition'], row['policy'])].append(row)
    summary = []
    for (condition, policy), rows in groups.items():
        means = {key: statistics.mean(row[key] for row in rows if row[key] is not None)
                 for key in ('packet_delivery_ratio', 'p95_delay_ms', 'handovers',
                             'ping_pong_within_2s', 'overload_cell_seconds', 'peak_dl_load')
                 if any(row[key] is not None for row in rows)}
        summary.append(dict(condition=condition, policy=policy, runs=len(rows), **means,
                            model_requests_completed=sum(row['model_requests_completed'] for row in rows),
                            early_requests_completed=sum(row['early_requests_completed'] for row in rows),
                            bridge_timeouts=sum(row['bridge_timeouts'] for row in rows)))
    (suite / 'summary.json').write_text(json.dumps(dict(trials=trials, summary=summary), indent=2))
    print(json.dumps(summary, indent=2))
